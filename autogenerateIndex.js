import {readdirSync, writeFileSync} from "node:fs";

const files = readdirSync("src")
  .filter(
    (f) =>
      f.endsWith(".ts") &&
      !f.endsWith(".d.ts") &&
      !f.endsWith(".test.ts") &&
      f !== "index.ts",
  )
  .sort();

const lines = files.map(
  (f) => `export * from "./${f.replace(/\.ts$/, ".js")}";`,
);

writeFileSync(
  "src/index.ts",
  `// Auto-generated by scripts/generateIndex.js. Do not edit.\n${lines.join("\n")}\n`,
);
